import struct
buf = struct.pack("i"*12, *list(range(12)))
x = memoryview(buf)
y = x.cast('i', shape=[2,2,3])
print(repr(y.tolist()))
print(repr(y.format))
print(repr(y.itemsize))
print(repr(len(y)))
print(repr(y.nbytes))
z = y.cast('b')
print(repr(z.format))
print(repr(z.itemsize))
print(repr(len(z)))
print(repr(z.nbytes))
buf = struct.pack("L"*6, *list(range(6)))
x = memoryview(buf)
y = x.cast('L', shape=[2,3])
print(repr(len(y)))
print(repr(y.nbytes))
print(repr(y.tolist()))
